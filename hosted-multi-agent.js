// ─── Hosted API client ───────────────────────────────────────────────────────

async function fetchDelegate(delegateId) {
  const res = await fetch(`${API_BASE}/sovereign/delegates/${delegateId}`, {
    headers: { 'x-api-key': API_KEY },
  })
  if (!res.ok) {
    const text = await res.text()
    throw new Error(`Failed to fetch delegate: ${res.status} ${text}`)
  }
  const response = await res.json()
  const delegate = response.delegate
  const localDelegate = loadLocalDelegate()

  // The stored delegate endpoint returns the signed authority body. The portal
  // export may also include unsigned domainSummary metadata that bots need when
  // constructing public records for hosted verification.
  if (localDelegate?.delegateId === delegate.delegateId) {
    return {
      ...delegate,
      ...(localDelegate.domainSummary ? { domainSummary: localDelegate.domainSummary } : {}),
      ...(localDelegate.avatarAddress ? { avatarAddress: localDelegate.avatarAddress } : {}),
    }
  }

  return delegate
}

function loadLocalDelegate() {
  if (!existsSync('mint-delegate.json')) return null
  try {
    return JSON.parse(readFileSync('mint-delegate.json', 'utf8'))
  } catch (err) {
    throw new Error(`Failed to read mint-delegate.json: ${err.message}`)
  }
}

async function loadDelegate() {
  if (DELEGATE_ID) return fetchDelegate(DELEGATE_ID)

  const localDelegate = loadLocalDelegate()
  if (localDelegate) return localDelegate

  throw new Error('Set AE_DELEGATE_ID or provide mint-delegate.json')
}

function stripDelegateMetadata(delegate) {
  const { domainSummary, ...signedDelegate } = delegate
  return signedDelegate
}

async function hostedMint(delegate, request) {
  const res = await fetch(`${API_BASE}/sovereign/mint`, {
    method: 'POST',
    headers: {
      'Content-Type': 'application/json',
      'x-api-key': API_KEY,
    },
    body: JSON.stringify({ delegate, request }),
  })
  if (!res.ok) {
    const text = await res.text()
    throw new Error(`Mint failed: ${res.status} ${text}`)
  }
  return res.json()
}

async function hostedVerify({ recordId, agentId, actionIndex, payload, signature, expectedActionEnvelopeHash }) {
  const res = await fetch(`${API_BASE}/sovereign/verify`, {
    method: 'POST',
    headers: {
      'Content-Type': 'application/json',
      'x-api-key': API_KEY,
    },
    body: JSON.stringify({
      ...(recordId ? { recordId } : { agentId }),
      actionIndex,
      payload,
      signature,
      expectedActionEnvelopeHash,
    }),
  })
  if (!res.ok) {
    const text = await res.text()
    throw new Error(`Verify failed: ${res.status} ${text}`)
  }
  return res.json()
}

// ─── Hosted bot ──────────────────────────────────────────────────────────────

class HostedBot {
  constructor({ delegate, mintMaterial, botSeed, botAddress, ownerUserId, agentIdPrefix }) {
    this.delegate = stripDelegateMetadata(delegate)
    this.domainSummary = delegate.domainSummary ?? null
    this.mintMaterial = Uint8Array.from(mintMaterial)
    this.botSeed = Uint8Array.from(botSeed)
    this.botAddress = botAddress
    this.ownerUserId = ownerUserId || this.delegate.avatarAddress || this.delegate.issuerAddress
    this.agentIdPrefix = agentIdPrefix
    this.actionIndex = this.delegate.actionIndexPolicy?.min ?? 0
    this.pendingVerifications = []
    this.generatedRecords = []
  }

  canExecute(operation) {
    return this.delegate.allowedOperations.includes(operation)
  }

  canRegisterRecords() {
    return Boolean(this.domainSummary && this.ownerUserId)
  }

  buildActionEnvelope(agentId, operation, resources, actionIndex, timeWindow, maxUses) {
    const domain = this.domainSummary
    return {
      type: 'agentenvelope.actionEnvelope',
      version: 1,
      agentId,
      domain: {
        domainId: domain.domainInfo.domainId,
        domainHash: domain.domainHash,
      },
      actionIndex,
      operation,
      resources,
      timeWindow,
      decayPolicy: { mode: 'BOTH' },
      limits: { maxUses, enforcement: 'external' },
    }
  }

  buildPublicRecord(agentAddress, actionEnvelope) {
    const domain = this.domainSummary
    const canonicalEnvelope = canonicalJSON(actionEnvelope)
    const actionEnvelopeHash = contentHash(canonicalEnvelope)
    const recordId = `ae-action-${contentHash({
      ownerUserId: this.ownerUserId,
      agentAddress,
      actionEnvelopeHash,
    }).slice(2, 22)}`

    return {
      type: 'agentenvelope.publicActionRecord',
      version: 1,
      recordId,
      ownerUserId: this.ownerUserId,
      custodyMode: 'remote-mint-delegate',
      verifierProfile: 'domain-action-envelope',
      status: 'active',
      createdAt: new Date().toISOString(),
      agentId: actionEnvelope.agentId,
      agentAddress,
      domain,
      actionEnvelope,
      canonicalActionEnvelope: canonicalEnvelope,
      actionEnvelopeHash,
      expiry: actionEnvelope.timeWindow.notAfter
        ? new Date(actionEnvelope.timeWindow.notAfter).toISOString()
        : null,
    }
  }

  async execute(operation, resources, payload) {
    // 1. Check authority locally first
    if (!this.canExecute(operation)) {
      return {
        executed: false,
        stage: 'authority_check',
        reason: `Operation '${operation}' not in delegate. Allowed: ${this.delegate.allowedOperations.join(', ')}`,
      }
    }

    // 2. Build mint request
    const now = Date.now()
    const agentId = `${this.agentIdPrefix}-${operation}-${this.actionIndex}`
    const actionIndex = this.actionIndex++
    const timeWindow = { notBefore: now, notAfter: now + 5 * 60 * 1000 }

    const request = buildMintRequest(Uint8Array.from(this.botSeed), this.delegate, {
      agentId,
      operation,
      resources,
      actionIndex,
      maxUses: 1,
      timeWindow,
      nonce: crypto.randomUUID(),
      requestedAt: new Date().toISOString(),
    })

    // 3. Verify request locally
    const localCheck = verifyMintRequest(request, this.delegate)
    if (!localCheck.valid) {
      return {
        executed: false,
        stage: 'local_verify',
        reason: `Local verification failed: ${localCheck.reason}`,
      }
    }

    // 4. POST /sovereign/mint — hosted governance
    let receipt
    try {
      receipt = await hostedMint(this.delegate, request)
    } catch (err) {
      return {
        executed: false,
        stage: 'hosted_mint',
        reason: err.message,
      }
    }

    // 5. Derive capability locally from mint material
    const capability = mintActionCapability(
      Uint8Array.from(this.mintMaterial),
      this.delegate,
      request
    )

    // 6. Sign the action
    const action = {
      operation,
      resources,
      payload,
      timestamp: new Date().toISOString(),
    }
    const actionSeed = hexToBytes(capability.actionSeedHex)
    const signature = signAction(actionSeed, action)

    // 7. Verify locally
    const verification = verifyAction({
      message: action,
      signature,
      expectedAddress: capability.agentAddress,
    })

    if (!verification.valid) {
      return {
        executed: false,
        stage: 'local_signature',
        reason: 'Local signature verification failed',
      }
    }

    // 8. Generate a seedless public record manifest when domain metadata is
    // available. Publishing it remains an account-governed portal operation.
    let recordId = null
    let actionEnvelopeHash = null
    if (this.canRegisterRecords()) {
      const actionEnvelope = this.buildActionEnvelope(agentId, operation, resources, actionIndex, timeWindow, 1)
      const record = this.buildPublicRecord(capability.agentAddress, actionEnvelope)
      actionEnvelopeHash = record.actionEnvelopeHash
      this.generatedRecords.push(record)
    }

    // Store for later hosted verification
    this.pendingVerifications.push({
      agentId,
      actionIndex,
      action,
      signature,
      capability,
      receipt,
      recordId,
      actionEnvelopeHash,
    })

    return {
      executed: true,
      agentId,
      agentAddress: capability.agentAddress,
      signature: signature.slice(0, 20) + '...',
      receipt: {
        id: receipt.mintId || receipt.receiptId || receipt.requestId,
        valid: receipt.valid,
      },
      recordId,
    }
  }

  async verifyPending() {
    const results = []
    for (const pending of this.pendingVerifications) {
      if (!pending.recordId) {
        results.push({
          agentId: pending.agentId,
          valid: false,
          skipped: true,
          error: 'No hosted public record was registered for this action',
        })
        continue
      }

      try {
        const report = await hostedVerify({
          recordId: pending.recordId,
          agentId: pending.agentId,
          actionIndex: pending.actionIndex,
          payload: pending.action,
          signature: pending.signature,
          expectedActionEnvelopeHash: pending.actionEnvelopeHash,
        })
        results.push({
          agentId: pending.agentId,
          valid: report.valid,
          checks: report.checks,
        })
      } catch (err) {
        results.push({
          agentId: pending.agentId,
          valid: false,
          error: err.message,
        })
      }
    }
    return results
  }
}

// ─── Tool router ─────────────────────────────────────────────────────────────

const toolMapping = {
  read_thread: {
    operation: 'read-thread',
    resources: (input) => [`thread:${input.threadId}`],
  },
  send_message: {
    operation: 'send-message',
    resources: (input) => [`thread:${input.threadId}`],
  },
  issue_refund: {
    operation: 'issue-refund',
    resources: (input) => [`order:${input.orderId}`],
  },
}

async function routeToolCall(bot, toolName, toolInput) {
  const mapping = toolMapping[toolName]
  if (!mapping) {
    return { executed: false, reason: `Unknown tool: ${toolName}` }
  }
  return bot.execute(mapping.operation, mapping.resources(toolInput), toolInput)
}

// ─── Simulated tool outputs ──────────────────────────────────────────────────

function simulateToolOutput(toolName, toolInput, result) {
  if (!result.executed) {
    return { error: 'AUTHORITY_DENIED', message: result.reason }
  }
  if (toolName === 'read_thread') {
    return {
      threadId: toolInput.threadId,
      messages: [
        { from: 'customer', text: 'Hi, I need a refund for order ORD-456. Charged $99.99, never received it.' },
      ],
    }
  }
  if (toolName === 'issue_refund') {
    return { success: true, refundId: 'REF-' + Date.now(), amount: toolInput.amount }
  }
  if (toolName === 'send_message') {
    return { success: true, messageId: 'MSG-' + Date.now() }
  }
  return { success: true }
}

// ─── Demo ────────────────────────────────────────────────────────────────────

const MODEL_ID = process.env.BEDROCK_MODEL_ID || 'us.anthropic.claude-sonnet-4-5-20250929-v1:0'

const SYSTEM_PROMPT = `You are a support agent with three tools:
- read_thread: Read support threads
- send_message: Send messages to customers
- issue_refund: Process refunds

For a refund request: read the thread, process the refund, then confirm with the customer.`

async function runDemo() {
  console.log('╔══════════════════════════════════════════════════════════════════╗')
  console.log('║  Hosted Tool Workflow: Portal Governance + Signed Receipts      ║')
  console.log('╚══════════════════════════════════════════════════════════════════╝')
  console.log()

  // 1. Check credentials
  if (!API_KEY || !DELEGATE_ID || !BOT_KEY || !MINT_MATERIAL_HEX) {
    console.error('Missing credentials. Set in .env.local:')
    console.error('  AE_API_KEY, AE_DELEGATE_ID, AE_BOT_KEY, AE_MINT_MATERIAL')
    process.exit(1)
  }

  // 2. Fetch delegate from hosted API
  console.log('1. Fetch delegate from hosted API')
  console.log('   ─────────────────────────────────────────────────────────────')
  console.log(DELEGATE_ID
    ? `   GET /sovereign/delegates/${DELEGATE_ID}`
    : '   Loading mint-delegate.json')

  const delegate = await loadDelegate()

  // Verify delegate locally
  const signedDelegate = stripDelegateMetadata(delegate)
  const delegateCheck = verifyMintDelegate(signedDelegate, signedDelegate.issuerAddress)
  if (!delegateCheck.valid) {
    console.error(`   ✗ Delegate verification failed: ${delegateCheck.reason}`)
    process.exit(1)
  }

  console.log(`   ✓ Delegate verified`)
  console.log(`   Issuer:     ${signedDelegate.issuerAddress}`)
  console.log(`   Operations: ${signedDelegate.allowedOperations.join(', ')}`)
  console.log(`   Resources:  ${signedDelegate.allowedResources.join(', ')}`)
  console.log()

  // 3. Initialize bot
  console.log('2. Initialize bot with delegate + mint material')
  console.log('   ─────────────────────────────────────────────────────────────')

  const botSeed = hexToBytes(BOT_KEY)
  const botAddress = seedAddress(botSeed)
  const mintMaterial = hexToBytes(MINT_MATERIAL_HEX)

  const bot = new HostedBot({
    delegate,
    mintMaterial,
    botSeed,
    botAddress,
    ownerUserId: OWNER_USER_ID,
    agentIdPrefix: BOT_ID,
  })

  console.log(`   Bot address: ${botAddress}`)
  console.log(`   Agent id prefix: ${BOT_ID}`)
  if (bot.canRegisterRecords()) {
    console.log(`   ✓ Ready to mint and generate seedless public record manifests`)
    console.log(`   Record registration remains account-owned and Cognito authenticated`)
    console.log(`   Record owner: ${bot.ownerUserId}`)
  } else {
    console.log(`   ✓ Ready to mint (no domainSummary - records won't be registered)`)
  }
  console.log()

  // 4. User prompt
  const userPrompt = 'Customer in thread customer-123 wants a refund for order ORD-456 ($99.99). Handle it.'
  console.log('3. User prompt')
  console.log('   ─────────────────────────────────────────────────────────────')
  console.log(`   "${userPrompt}"`)
  console.log()

  // 5. Agent loop
  console.log('4. Agent loop (LLM → Bot → Hosted API)')
  console.log('   ═════════════════════════════════════════════════════════════')

  const messages = [{ role: 'user', content: [{ text: userPrompt }] }]
  const allResults = []
  let turn = 0

  while (turn < 5) {
    turn++
    console.log()
    console.log(`   ┌─ Turn ${turn} ─────────────────────────────────────────────────┐`)

    const response = await converse({
      modelId: MODEL_ID,
      system: SYSTEM_PROMPT,
      messages,
      tools,
    })

    const assistantMessage = response.output.message
    messages.push(assistantMessage)

    const textContent = assistantMessage.content.find(c => c.text)
    if (textContent) {
      console.log()
      console.log(`   LLM: "${textContent.text}"`)
    }

    const toolCalls = assistantMessage.content.filter(c => c.toolUse)
    if (toolCalls.length === 0) {
      console.log()
      console.log('   └─ LLM finished ─────────────────────────────────────────────┘')
      break
    }

    console.log()
    console.log('   Tool calls (each goes through hosted mint):')
    const toolResults = []

    for (const { toolUse } of toolCalls) {
      console.log()
      console.log(`     ${toolUse.name}`)
      console.log(`     Input: ${JSON.stringify(toolUse.input)}`)

      const result = await routeToolCall(bot, toolUse.name, toolUse.input)
      allResults.push({ tool: toolUse.name, result })

      if (result.executed) {
        console.log(`     ✓ EXECUTED`)
        console.log(`       Agent:   ${result.agentAddress}`)
        console.log(`       Sig:     ${result.signature}`)
        console.log(`       Receipt: ${result.receipt.id} (valid: ${result.receipt.valid})`)
        if (result.recordId) {
          console.log(`       Record:  ${result.recordId} (registered)`)
        }
      } else {
        console.log(`     ✗ BLOCKED at ${result.stage}`)
        console.log(`       Reason: ${result.reason}`)
      }

      const output = simulateToolOutput(toolUse.name, toolUse.input, result)
      toolResults.push({
        toolResult: {
          toolUseId: toolUse.toolUseId,
          content: [{ json: output }],
        },
      })
    }

    messages.push({ role: 'user', content: toolResults })
    console.log()
    console.log('   └─ Results sent back to LLM ────────────────────────────────┘')
  }

  if (bot.generatedRecords.length > 0) {
    writeFileSync(HOSTED_RECORDS_PATH, JSON.stringify({
      type: 'agentenvelope.generatedPublicRecords',
      version: 1,
      generatedAt: new Date().toISOString(),
      registration: {
        route: 'POST /sovereign/agents/register',
        auth: 'Cognito account governance',
        note: 'These seedless records are public metadata. Publish them from the owner account, not from a bot API key.',
      },
      records: bot.generatedRecords,
    }, null, 2))
    console.log()
    console.log(`   Generated ${bot.generatedRecords.length} public record manifest(s): ${HOSTED_RECORDS_PATH}`)
  }

  // 6. Hosted verification
  console.log()
  console.log('5. Hosted verification (POST /sovereign/verify)')
  console.log('   ─────────────────────────────────────────────────────────────')

  const verifications = await bot.verifyPending()
  for (const v of verifications) {
    if (v.valid) {
      console.log(`   ✓ ${v.agentId}: valid`)
    } else {
      console.log(`   ✗ ${v.agentId}: ${v.error || 'invalid'}`)
    }
  }

  // 7. Summary
  console.log()
  console.log('6. Summary')
  console.log('   ─────────────────────────────────────────────────────────────')
  const executed = allResults.filter(r => r.result.executed)
  const blocked = allResults.filter(r => !r.result.executed)
  console.log(`   Executed: ${executed.length} (${executed.map(r => r.tool).join(', ') || 'none'})`)
  console.log(`   Blocked:  ${blocked.length} (${blocked.map(r => r.tool).join(', ') || 'none'})`)
  if (bot.generatedRecords.length > 0) {
    console.log(`   Records:  ${bot.generatedRecords.length} generated locally, 0 registered`)
    for (const record of bot.generatedRecords) {
      console.log(`             - ${record.recordId} (${record.agentId})`)
    }
  }
  console.log()
  console.log('   ┌─────────────────────────────────────────────────────────────┐')
  console.log('   │ Every mint went through POST /sovereign/mint.              │')
  console.log('   │ The hosted API verified delegate + bot + policy bounds.    │')
  console.log('   │ Receipts prove the mint was valid at that moment.          │')
  if (bot.generatedRecords.length > 0) {
    console.log('   │ Seedless public record manifests were generated locally.  │')
    console.log('   │ Registration is intentionally portal/account governed.    │')
    console.log('   │ Hosted record verification waits until records are live.  │')
  } else {
    console.log('   │ No public records were registered because domainSummary    │')
    console.log('   │ metadata was not available to this local script.           │')
  }
  console.log('   └─────────────────────────────────────────────────────────────┘')
  console.log()
}

runDemo().catch(console.error)
