/**
 * hosted-multi-agent.js — Hosted governance workflow for LLM tool use
 *
 * Uses the same support workflow as multi-agent.js, but runs every tool call
 * through one portal-issued delegate and the hosted API. For strict three-bot
 * separation, issue one hosted delegate per bot address; this compact example
 * keeps the portal setup to a single delegate.
 *
 *   POST /sovereign/mint            — mint capabilities through hosted governance
 *   POST /sovereign/verify          — verify signatures against hosted records
 *
 * Hosted mint uses API-key authentication because authority is derived from the
 * delegate and bot signatures. Record registration remains account-owned and
 * requires Cognito authentication. This example demonstrates mint receipts;
 * record-backed hosted verification works once the record is registered via the
 * portal.
 *
 * The hosted API enforces:
 *   - delegate signature validity
 *   - bot signature validity
 *   - operation ∈ delegate.allowedOperations
 *   - resource ∈ delegate.allowedResources
 *   - nonce replay protection
 *   - mint count limits
 *
 * Requires .env.local with:
 *   AE_API_KEY        — portal-issued API key
 *   AE_BOT_ID         — stable agent id prefix for minted hosted actions
 *   AE_DELEGATE_ID    — active delegate from portal
 *   AE_BOT_KEY        — bot identity key (generated by portal:setup)
 *   AE_MINT_MATERIAL  — mint material from portal
 *   AE_OWNER_USER_ID  — optional owner override for generated public records
 *
 * Optional:
 *   mint-delegate.json — exported delegate JSON with domainSummary metadata,
 *                        used for public record construction when present
 */

